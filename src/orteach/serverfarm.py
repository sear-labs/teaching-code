"""A two-stage stochastic program: size a server farm now, rent cloud compute later.

The teaching notebook ``notebooks/07_stochastic_and_newsvendor/server_farm.ipynb`` builds the
model by hand with ``addVars``, one constraint per scenario and machine type. This module builds
it once in matrix form with ``addMVar``, the form IE 5301's 2026 code uses, so the agreement
assertion also shows the two ways of writing it agree.

    first stage   buy[t]          machines of each type, bought before demand is seen (integer)
    second stage  rent[k, t]      cloud units rented in scenario k to cover the shortfall (integer)
    subject to    purchase cost <= budget, floor space <= space, buy + rent >= demand
    minimise      purchase cost + mean over scenarios of cloud cost

Both tables live in ``data/raw/``: ``server_farm_machines.csv`` (cost, space, cloud price per
type) and ``server_farm_demand.csv`` (50 scenarios), the latter generated by
``generate_demand`` from the seed recorded below.
"""
from __future__ import annotations

import csv
import math
import os
import random
from dataclasses import dataclass, field

import gurobipy as gp
import numpy as np

from . import paths, tolerance

MACHINES_CSV = "server_farm_machines.csv"   # resolved by paths.table() when read
DEMAND_CSV = "server_farm_demand.csv"

# The generating parameters, recorded so the table can be rebuilt exactly. random.Random rather
# than numpy, so the table does not depend on a numpy version's generator. With this seed and 50
# scenarios the optimal purchase is unique (checked 2026-10-27 by minimising and maximising each
# machine count over the optimal set); seed 7 with 40 scenarios is a counterexample, with ties.
DEMAND_SEED = 20261027
DEMAND_N = 50
DEMAND_MEAN_SD = {"cpu": (70.0, 10.0), "gpu": (8.0, 2.0), "tpu": (15.0, 4.0)}


@dataclass
class Machines:
    types: list
    purchase: dict          # type -> cost to buy one
    space: dict             # type -> floor space one takes
    cloud: dict             # type -> cost to rent one unit for the period


@dataclass
class Plan:
    buy: dict                               # type -> machines bought
    expected_cost: float                    # purchase + mean cloud bill over the scenarios
    rent: list = field(repr=False)          # per scenario: type -> units rented
    label: str = ""


def generate_demand(n=DEMAND_N, seed=DEMAND_SEED):
    rng = random.Random(seed)
    return [{t: round(max(rng.normalvariate(*DEMAND_MEAN_SD[t]), 0.0), 2) for t in DEMAND_MEAN_SD}
            for _ in range(n)]


def write_demand(path=None):
    path = path or os.path.join(paths.SOURCE_DIR, DEMAND_CSV)   # writes the clone's own table
    rows = generate_demand()
    with open(path, "w", newline="", encoding="utf-8") as f:
        w = csv.writer(f)
        w.writerow(["scenario"] + list(DEMAND_MEAN_SD))
        for k, d in enumerate(rows):
            w.writerow([k + 1] + [d[t] for t in DEMAND_MEAN_SD])
    return path


def load_demand(path=None) -> list:
    path = path or paths.table(DEMAND_CSV)
    with open(path, encoding="utf-8") as f:
        recs = list(csv.DictReader(f))
    return [{t: float(r[t]) for t in r if t != "scenario"} for r in recs]


def load_machines(path=None) -> Machines:
    path = path or paths.table(MACHINES_CSV)
    with open(path, encoding="utf-8") as f:
        recs = list(csv.DictReader(f))
    return Machines([r["machine"] for r in recs], {r["machine"]: float(r["purchase_cost"]) for r in recs},
                    {r["machine"]: float(r["space"]) for r in recs}, {r["machine"]: float(r["cloud_cost"]) for r in recs})


def rent_needed(demand_k: dict, buy: dict) -> dict:
    """Whole cloud units to cover one scenario's shortfall: the recourse, once buy is fixed."""
    return {t: max(0, math.ceil(demand_k[t] - buy[t] - tolerance.FEASIBILITY_ATOL)) for t in buy}


def score_plan(machines: Machines, demand: list, buy: dict, label="scored") -> Plan:
    """A purchase decided some other way, costed against every scenario: no solver needed."""
    rent = [rent_needed(d, buy) for d in demand]
    cost = sum(machines.purchase[t] * buy[t] for t in machines.types) + \
        sum(machines.cloud[t] * r[t] for r in rent for t in machines.types) / len(demand)
    return Plan(dict(buy), cost, rent, label)


def solve_two_stage(machines: Machines, demand: list, budget: float, space: float, env=None) -> Plan:
    """The stochastic program in matrix form (addMVar)."""
    T, K = machines.types, len(demand)
    c_buy = np.array([machines.purchase[t] for t in T])
    c_space = np.array([machines.space[t] for t in T])
    c_cloud = np.array([machines.cloud[t] for t in T])
    D = np.array([[d[t] for d in demand] for t in T])          # types x scenarios
    with gp.Model(env=env) as m:
        tolerance.apply(m)
        x = m.addMVar(len(T), vtype=gp.GRB.INTEGER, name="buy")
        y = m.addMVar((len(T), K), vtype=gp.GRB.INTEGER, name="rent")
        m.addConstr(c_buy @ x <= budget, name="budget")
        m.addConstr(c_space @ x <= space, name="space")
        m.addConstrs((x + y[:, k] >= D[:, k] for k in range(K)), name="demand")
        m.setObjective(c_buy @ x + gp.quicksum(c_cloud @ y[:, k] for k in range(K)) / K, gp.GRB.MINIMIZE)
        m.optimize()
        if m.Status != gp.GRB.OPTIMAL:
            raise RuntimeError("server farm model ended with status %d" % m.Status)
        buy = {t: int(round(v)) for t, v in zip(T, x.X)}
    return score_plan(machines, demand, buy, "stochastic")


def solve_mean_value(machines: Machines, demand: list, budget: float, space: float, env=None) -> Plan:
    """Plan for average demand as if it were certain, then cost that purchase honestly against
    every scenario. The gap to solve_two_stage is the value of the stochastic solution."""
    mean = {t: sum(d[t] for d in demand) / len(demand) for t in machines.types}
    plan = solve_two_stage(machines, [mean], budget, space, env=env)
    return score_plan(machines, demand, plan.buy, "mean value")
